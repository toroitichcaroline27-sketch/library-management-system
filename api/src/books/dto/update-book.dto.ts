import { IsString, IsNotEmpty, IsInt, IsOptional, Min } from 'class-validator';

// Same rules as CreateBookDto, but every field is optional (PATCH).
export class UpdateBookDto {
  @IsOptional()
  @IsString()
  @IsNotEmpty()
  title?: string;

  @IsOptional()
  @IsString()
  @IsNotEmpty()
  author?: string;

  @IsOptional()
  @IsString()
  @IsNotEmpty()
  isbn?: string;

  @IsOptional()
  @IsInt()
  @Min(1)
  totalCopies?: number;

  @IsOptional()
  @IsInt()
  genreId?: number;
}
